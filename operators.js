//ADDITION (+)
const a = 12;
const b = 20;
const c = a + b
console.log(c);

//CONCATENATION
const apple = '100'
const bannana = '50'
console.log(apple + bannana);

const fName = 'Peter'
const lName = 'Paul'
const mName = 'John'
console.log(fName + lName + mName);


//SUBTRACTION OPERATOR (-)
const d = 100
const e = 50
const f = e - d
console.log(f);

console.log(100 - 50);

//DIVISION OPERATOR (/)
const g = 20
const h = 10
console.log(g/h);

//MULTIPLICATION OPERATOR (*)
console.log(20*4);

//EXPONENTIAL OPERATORS (**)
const i = 10
console.log(i**3)

//MODULUS (%)
const j = 10
const k = 3
console.log(j%k);

//COMPARISON OPERATORS

//GREATER(>) THAN
const l = 10
const m = 12
console.log(l>m);

//LESS THAN (<)
console.log(20<100);

//GREATER THAN OR EQUAL TO (>=)
console.log(10 >= 10);

//LESS THAN OR EQUAL TO (<=)
console.log(100<=10);

// EQUALITY OP(==)
const n = 12
const o = 14
console.log(n==o);

console.log('10' ==10);

//STRICT EQUALITY OPERATOR (Checks for value and the data type)(===)
const p ='19'
const q =19
console.log(p === q);

//INEQUALITY (not equal to)(!=)
console.log(10 != 8);

console.log(10!='10');

//STRICT INEQUALITY(!==)
console.log(10 !== '10');
console.log(10!==4);


//LOGICAL OPERATORS
//OR
console.log(true || true);

console.log(20>10 || 5>3);

//AND
const personAge = 20
console.log(personAge >= 18 && personAge <= 65, 'and');
let Age = 70
console.log(Age >= 18 && Age <= 65, 'and');

//NOT
console.log(!true);